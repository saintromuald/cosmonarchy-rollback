#!/usr/bin/env bash
# machine-setup.sh — prepare this machine for the desync farm (idempotent).
#
#   1. builds the rollback plugin and installs it into the master tree;
#   2. clones the master Cosmonarchy tree into per-slot A/B trees (full copies:
#      the game writes logs/replays/registry, so hardlink sharing is unsafe);
#   3. writes $FARMDIR/farm.local.conf (slots sized to this machine's cores/RAM).
#
# Usage: machine-setup.sh [--slots N] [--master ~/Games/cosmonarchy]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONF="$ROOT/cmscripts/farm.conf"
[ -f "$CONF" ] && . "$CONF"
FARMDIR="${FARMDIR:-$HOME/Games/cosmo-farm}"
MASTER="${MASTER:-$HOME/Games/cosmonarchy}"
BUILD="${FARM_BUILD:-Release}"
SLOTS="${SLOTS_ARG:-}"

while [ $# -gt 0 ]; do
    case "$1" in
        --slots) SLOTS="$2"; shift 2 ;;
        --master) MASTER="$2"; shift 2 ;;
        *) echo "unknown arg: $1" >&2; exit 2 ;;
    esac
done

CORE_THREADS=$(nproc)
MEM_GB=$(( $(awk '/MemTotal/ {print int($2/1024/1024)}' /proc/meminfo) ))
# Each pair: 2 game processes + 2 Xvfb; budget ~1.25 threads and ~2.2 GB per process,
# and keep 2 threads + 4 GB for the system.
if [ -z "$SLOTS" ]; then
    by_cpu=$(( (CORE_THREADS - 2) / 5 ))
    by_mem=$(( (MEM_GB - 4) / 4 ))
    SLOTS=$(( by_cpu < by_mem ? by_cpu : by_mem ))
    SLOTS=$(( SLOTS < 1 ? 1 : SLOTS ))
fi

MBASE="$MASTER/prefix/drive_c/Cosmonarchy"
[ -d "$MBASE/$BUILD" ] || { echo "missing master game: $MBASE/$BUILD" >&2; exit 1; }
[ -f "$MBASE/Starcraft/StarCraft.exe" ] || { echo "missing stock StarCraft.exe in $MBASE/Starcraft" >&2; exit 1; }

echo "== building the rollback plugin"
PROFILE=dev "$ROOT/tools/build.sh" >/dev/null
DLL="$ROOT/target/i686-pc-windows-msvc/debug/cosmo_rollback.dll"
[ -f "$DLL" ] || { echo "plugin build failed" >&2; exit 1; }

echo "== machine: $CORE_THREADS threads, ${MEM_GB} GB RAM -> $SLOTS slots ($((SLOTS * 2)) trees)"
mkdir -p "$FARMDIR/trees" "$FARMDIR/runs" "$FARMDIR/streams"

for s in $(seq 0 $((SLOTS - 1))); do
    for side in a b; do
        TREE="$FARMDIR/trees/slot$s-$side"
        PLUGDIR="$TREE/prefix/drive_c/Cosmonarchy/$BUILD/plugins"
        # `cp -a` on a symlink copies the symlink; resolve first so every slot
        # gets a REAL, independent tree (a shared prefix breaks everything).
        MASTER_REAL="$(readlink -f "$MASTER")"
        if [ -L "$TREE" ] || [ ! -d "$TREE/prefix" ]; then
            echo "  slot$s-$side: cloning $MASTER_REAL (this can take a minute)"
            rm -rf "$TREE"
            cp -a "$MASTER_REAL" "$TREE"
        fi
        mkdir -p "$PLUGDIR"
        # Attribution: the farm hunts *upstream* desyncs first, so the Plus
        # plugin and its config stay out of the farm trees.
        rm -f "$PLUGDIR/zz-cosmo-plus.qdp" "$PLUGDIR/cosmo_plus.conf"
        if [ ! -f "$PLUGDIR/zz-cosmo-rollback.qdp" ] || \
           [ "$(stat -c %Y "$PLUGDIR/zz-cosmo-rollback.qdp")" -lt "$(stat -c %Y "$DLL")" ]; then
            cp "$DLL" "$PLUGDIR/zz-cosmo-rollback.qdp"
            echo "  slot$s-$side: plugin installed"
        else
            echo "  slot$s-$side: present, plugin current"
        fi
    done
done

cat >"$FARMDIR/farm.local.conf" <<EOF
# machine-local farm config (generated by machine-setup.sh on $(hostname), $(date -I))
FARM_SLOTS=$SLOTS
EOF
echo "== wrote $FARMDIR/farm.local.conf"

echo
echo "setup done. next:  cmscripts/farmctl run-once   # one manual pair run"
echo "                   cmscripts/farmctl install     # systemd timer (overnight)"
